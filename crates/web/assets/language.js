export const CATALOGS = Object.freeze({ en: EN, fr: FR, es: ES, de: DE });

export function isSupportedLanguage(value) {
  return typeof value === "string" && SUPPORTED_LANGUAGES.includes(value);
}

export function loadLanguage(storage) {
  try {
    const value = storage?.getItem(LANGUAGE_STORAGE_KEY);
    return isSupportedLanguage(value) ? value : "en";
  } catch {
    return "en";
  }
}

export function saveLanguage(storage, language) {
  if (!isSupportedLanguage(language)) return false;
  try {
    storage?.setItem(LANGUAGE_STORAGE_KEY, language);
    return Boolean(storage);
  } catch {
    return false;
  }
}

export function translate(language, key, values = {}) {
  const locale = isSupportedLanguage(language) ? language : "en";
  const template = CATALOGS[locale][key] ?? CATALOGS.en[key];
  if (typeof template !== "string") return "Text unavailable";
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => {
    const value = values[name];
    return value === undefined || value === null ? match : String(value);
  });
}

const ID_ATTRIBUTE_KEYS = Object.freeze({
  "room-config-open": { "aria-label": "room.settings", title: "room.settings" },
  "leave-room": { "aria-label": "room.leave", title: "room.leave" },
  "game-menu": { "aria-label": "game.exit_menu", title: "game.menu_title" },
});

export function applyTranslations(root, language) {
  if (!root?.querySelectorAll) return;
  const elements = [];
  if (root.matches?.("[data-i18n], [data-i18n-aria-label], [data-i18n-title], [data-i18n-placeholder]")) {
    elements.push(root);
  }
  elements.push(...root.querySelectorAll("[data-i18n], [data-i18n-aria-label], [data-i18n-title], [data-i18n-placeholder]"));
  for (const element of elements) {
    if (element.dataset.i18n) element.textContent = translate(language, element.dataset.i18n);
    for (const [dataName, attribute] of [
      ["i18nAriaLabel", "aria-label"],
      ["i18nTitle", "title"],
      ["i18nPlaceholder", "placeholder"],
    ]) {
      const key = element.dataset[dataName];
      if (key) element.setAttribute(attribute, translate(language, key));
    }
  }
  for (const [id, attributes] of Object.entries(ID_ATTRIBUTE_KEYS)) {
    const element = root.getElementById?.(id);
    if (!element) continue;
    for (const [attribute, key] of Object.entries(attributes)) element.setAttribute(attribute, translate(language, key));
  }
}
